package com.minecraftindustrialcomplex.deeptime.ore;

import com.minecraftindustrialcomplex.deeptime.DeepTime;
import com.minecraftindustrialcomplex.deeptime.worldgen.GeologicChunkGenerator;
import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderSet;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.dimension.LevelStem;
import net.minecraft.world.level.levelgen.GenerationStep;
import net.minecraft.world.level.levelgen.placement.PlacedFeature;
import net.neoforged.neoforge.common.world.BiomeModifier;
import net.neoforged.neoforge.common.world.ModifiableBiomeInfo;
import net.neoforged.neoforge.server.ServerLifecycleHooks;

import java.util.List;

/**
 * {@code deeptime:claim_ores} (plan §7.7): in Deep Time worlds, removes the scatter of the
 * materials Deep Time simulates and, with {@code claim_rock_features} (default on, plan Q4), the
 * random rock blobs; {@link ClaimRules} decides per feature. Shipped as
 * {@code data/deeptime/neoforge/biome_modifier/claim_ores.json} for {@code #minecraft:is_overworld}.
 *
 * <p><b>Scope.</b> NeoForge applies biome modifiers per server, not per dimension, and has no
 * per-world datapack toggle. {@code ServerLifecycleHooks.handleServerAboutToStart} sets the current
 * server and then runs the modifiers, so the modifier reads that server's overworld level stem and
 * does nothing unless its generator is Deep Time's: a Deep Time world loses the claimed features
 * everywhere, any other world keeps them. (A Deep Time level inside a non-Deep-Time world, like the
 * GameTest dimensions, keeps them too.)
 *
 * @param biomes            where it applies
 * @param claimRockFeatures remove rock-blob features too
 * @param materials         more claimed materials (the pack's; the deposit types and scatter list
 *                          are always claimed)
 * @param rockFeatures      placed or configured feature ids that are rock blobs even though their
 *                          blocks cannot be read (removed with {@code claimRockFeatures})
 * @param keep              placed feature ids never removed
 * @param oreFeatureTypes   more ore-shaped feature types to judge (a pack's custom ore features;
 *                          {@link ClaimRules#DEFAULT_ORE_TYPES} always are)
 */
public record ClaimOresBiomeModifier(HolderSet<Biome> biomes, boolean claimRockFeatures, List<ResourceLocation> materials,
                                     List<ResourceLocation> rockFeatures, List<ResourceLocation> keep,
                                     List<ResourceLocation> oreFeatureTypes) implements BiomeModifier {

    public static final MapCodec<ClaimOresBiomeModifier> CODEC = RecordCodecBuilder.mapCodec(i -> i.group(
            Biome.LIST_CODEC.fieldOf("biomes").forGetter(ClaimOresBiomeModifier::biomes),
            Codec.BOOL.optionalFieldOf("claim_rock_features", true).forGetter(ClaimOresBiomeModifier::claimRockFeatures),
            ResourceLocation.CODEC.listOf().optionalFieldOf("materials", List.of()).forGetter(ClaimOresBiomeModifier::materials),
            ResourceLocation.CODEC.listOf().optionalFieldOf("rock_features", List.of()).forGetter(ClaimOresBiomeModifier::rockFeatures),
            ResourceLocation.CODEC.listOf().optionalFieldOf("keep", List.of()).forGetter(ClaimOresBiomeModifier::keep),
            ResourceLocation.CODEC.listOf().optionalFieldOf("ore_feature_types", List.of())
                    .forGetter(ClaimOresBiomeModifier::oreFeatureTypes)
    ).apply(i, ClaimOresBiomeModifier::new));

    /** True when {@code server}'s overworld is generated by Deep Time. */
    public static boolean deepTimeWorld(MinecraftServer server) {
        if (server == null)
            return false;
        var stems = server.registryAccess().registry(Registries.LEVEL_STEM);
        if (stems.isEmpty())
            return false;
        LevelStem overworld = stems.get().get(LevelStem.OVERWORLD);
        return overworld != null && overworld.generator() instanceof GeologicChunkGenerator;
    }

    @Override
    public void modify(Holder<Biome> biome, Phase phase, ModifiableBiomeInfo.BiomeInfo.Builder builder) {
        if (phase != Phase.REMOVE || !biomes.contains(biome))
            return;
        MinecraftServer server = ServerLifecycleHooks.getCurrentServer();
        if (!deepTimeWorld(server))
            return;
        ClaimRules rules = ClaimRules.forServer(server, this);
        var settings = builder.getGenerationSettings();
        for (GenerationStep.Decoration step : GenerationStep.Decoration.values()) {
            settings.getFeatures(step).removeIf(h -> {
                ClaimRules.Verdict v = rules.verdict(h);
                if (v == ClaimRules.Verdict.KEEP)
                    return false;
                ResourceLocation id = h.unwrapKey().map(ResourceKey::location)
                        .orElse(ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "direct"));
                ClaimRules.recordRemoved(id, v);
                return true;
            });
        }
    }

    @Override
    public MapCodec<? extends BiomeModifier> codec() {
        return CODEC;
    }

    /** Placed feature holders of a biome, for tests. */
    public static List<Holder<PlacedFeature>> features(Biome biome) {
        return biome.getGenerationSettings().features().stream().flatMap(HolderSet::stream).toList();
    }
}
