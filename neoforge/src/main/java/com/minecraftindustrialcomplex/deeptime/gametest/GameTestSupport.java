package com.minecraftindustrialcomplex.deeptime.gametest;

import com.minecraftindustrialcomplex.deeptime.DeepTime;
import net.minecraft.core.BlockPos;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.RegisterGameTestsEvent;

/**
 * Shared GameTest constants and the dev-only wiring.
 *
 * <p>Deep Time runs GameTests in two runtimes, each with its own namespace (plan §9.4):
 * the GameTest server ({@code ./gametest.sh}, namespace {@value #NS}) and the dev planet
 * server ({@code ./gametest-planet.sh}, namespace {@value #NS_PLANET}). NeoForge collects
 * {@code @GameTestHolder} classes from the annotation scan data and registers only those
 * whose namespace is enabled, so planet-only holders never run in the flat GameTest world.
 * Holders must keep optional-mod types (Sable, Create) out of their method signatures:
 * registration loads every declared method of an enabled holder.
 */
public final class GameTestSupport {

    public static final String NS = DeepTime.MODID;
    public static final String NS_PLANET = "deeptime_planet";

    /**
     * The template every test runs in: a 5x5x5 box of air on a one-block floor, generated by
     * {@code tools/make_test_structure.py} and shipped once per namespace under
     * {@code data/<namespace>/structure/}. NeoForge 21.1 throws "Missing test structure"
     * on an empty template name, so a template is not optional.
     */
    public static final String TEMPLATE = "empty_5x5x5";

    public static final BlockPos CENTRE = new BlockPos(2, 1, 2);

    private GameTestSupport() {}

    /** True in the two dev GameTest runtimes (both set {@code -Ddeeptime.gametest=true}). */
    public static boolean enabled() {
        return Boolean.getBoolean("deeptime.gametest");
    }

    public static void init(IEventBus modBus) {
        if (!enabled())
            return;
        modBus.addListener(RegisterGameTestsEvent.class,
                e -> DeepTime.LOGGER.info("[gametest] Deep Time GameTest support enabled"));
    }
}
