package com.minecraftindustrialcomplex.deeptime.gametest;

import com.minecraftindustrialcomplex.deeptime.DeepTime;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.minecraft.world.level.Level;
import net.neoforged.bus.api.IEventBus;
import net.minecraft.gametest.framework.GlobalTestReporter;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.AddPackFindersEvent;
import net.neoforged.neoforge.event.server.ServerStartingEvent;
import net.neoforged.neoforge.event.RegisterGameTestsEvent;

/**
 * Shared GameTest constants and the dev-only wiring.
 *
 * <p>Deep Time runs GameTests in two runtimes, each with its own namespace (plan §9.4):
 * the GameTest server ({@code ./gametest.sh}, namespace {@value #NS}) and the dev planet
 * server ({@code ./gametest-planet.sh}, namespace {@value #NS_PLANET}). NeoForge collects
 * {@code @GameTestHolder} classes from the annotation scan data and registers only those
 * whose namespace is enabled, so planet-only holders never run in the flat GameTest world.
 * Holders must keep optional-mod types (Sable, Create) out of their method signatures:
 * registration loads every declared method of an enabled holder.
 */
public final class GameTestSupport {

    public static final String NS = DeepTime.MODID;
    public static final String NS_PLANET = "deeptime_planet";

    /**
     * The template every test runs in: a 5x5x5 box of air on a one-block floor, generated by
     * {@code tools/make_test_structure.py} and shipped once per namespace under
     * {@code data/<namespace>/structure/}. NeoForge 21.1 throws "Missing test structure"
     * on an empty template name, so a template is not optional.
     */
    public static final String TEMPLATE = "empty_5x5x5";

    public static final BlockPos CENTRE = new BlockPos(2, 1, 2);

    /** The analytic test terrain's level (C = 16,384), defined by the gametest pack (plan §9.4). */
    public static final ResourceKey<Level> TEST_PLANET =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_planet"));

    /** The synthetic world-data level (C = 1,024, folder {@code deeptime-test}; gametest.sh writes it). */
    public static final ResourceKey<Level> TEST_PLANET_DATA =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_planet_data"));

    /**
     * The lake-test level (C = 1,024, folder {@code deeptime-lake}; gametest.sh writes it): a fixed
     * biome with no carvers and no features, {@code deeptime:test_bare}, so nothing but the
     * generator touches the basin (plan §9.4, P0-13).
     */
    public static final ResourceKey<Level> TEST_LAKE =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_lake"));

    /**
     * The synthetic deposit world (P1-15; C = 4,096, folder {@code deeptime-deposits}; gametest.sh
     * writes it with {@code deeptime run --preset deposits_world_4k.json}): a fixed biome,
     * {@code deeptime:test_ores}, whose only features are the deposits and the background scatter.
     */
    public static final ResourceKey<Level> TEST_DEPOSITS =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_deposits"));

    /**
     * A real baked planet (P1-08; C = 4,096, folder {@code deeptime-real}; gametest.sh writes it
     * with {@code deeptime run --preset tests/presets/planet_world_4k.json} and its parity fixture
     * with {@code deeptime parity}): every stage of the pipeline, the pack's biomes and surface
     * rules, no caves ({@code deeptime:planet_nocaves}).
     */
    public static final ResourceKey<Level> TEST_PLANET_REAL =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_planet_real"));

    /**
     * The real planet's world data again (folder {@code deeptime-real}) with the lake level's bare
     * biome, no carvers, no features and no caves (P1-22): only the generator's passes touch its
     * rivers and lakes, so {@code RiverGameTests.riversHold} sees exactly what the water pass built.
     */
    public static final ResourceKey<Level> TEST_RIVERS =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_rivers"));

    /** A second level over the same deposit world data, for the regeneration check. */
    public static final ResourceKey<Level> TEST_DEPOSITS_TWIN =
            ResourceKey.create(Registries.DIMENSION, ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "test_deposits_twin"));

    private GameTestSupport() {}

    /** True in the two dev GameTest runtimes (both set {@code -Ddeeptime.gametest=true}). */
    public static boolean enabled() {
        return Boolean.getBoolean("deeptime.gametest");
    }

    public static void init(IEventBus modBus) {
        if (!enabled())
            return;
        modBus.addListener(RegisterGameTestsEvent.class,
                e -> DeepTime.LOGGER.info("[gametest] Deep Time GameTest support enabled"));
        modBus.addListener(AddPackFindersEvent.class, GameTestSupport::addTestPack);
        extraDatapack().ifPresent(dir -> modBus.addListener(AddPackFindersEvent.class, e -> addExtraPack(e, dir)));
        ChunkCensus.register();
        // The planet server is a normal dedicated server with /test enabled: give it a reporter
        // that logs passes (the GameTest server logs its own summary).
        if (Boolean.getBoolean("neoforge.enableGameTest"))
            NeoForge.EVENT_BUS.addListener(ServerStartingEvent.class, e -> {
                GlobalTestReporter.replaceWith(DeepTimeTestReporter.INSTANCE);
                DeepTime.LOGGER.info("[gametest] Deep Time test reporter installed");
            });
    }

    /**
     * The gametest pack ({@code src/gametest/resources/deeptime_gametest/}): test dimensions and
     * biomes. It is part of the mod only in dev runs (the gametest source set), and required
     * (always active) there. The GameTest server enables every available pack anyway.
     */
    private static void addTestPack(AddPackFindersEvent event) {
        event.addPackFinders(ResourceLocation.fromNamespaceAndPath(DeepTime.MODID, "deeptime_gametest"),
                PackType.SERVER_DATA, Component.literal("Deep Time GameTest"), PackSource.BUILT_IN, true,
                Pack.Position.TOP);
    }

    /** The pack id {@link #addExtraPack} gives the extra datapack. */
    public static final String EXTRA_PACK_ID = "deeptime_extra";

    /**
     * {@code -Ddeeptime.extraDatapack=<folder>}: one more datapack folder, from outside the mod
     * (P1-12: the MIC rock-tag datapack for {@code ./gametest.sh -PwithMic}). Honoured only together
     * with {@code -Ddeeptime.gametest=true}; {@link #init} never runs otherwise.
     */
    public static java.util.Optional<java.nio.file.Path> extraDatapack() {
        String p = System.getProperty("deeptime.extraDatapack", "");
        return p.isBlank() ? java.util.Optional.empty() : java.util.Optional.of(java.nio.file.Path.of(p).toAbsolutePath().normalize());
    }

    /** True when the extra datapack is among the server's selected packs. */
    public static boolean extraDatapackActive(net.minecraft.server.MinecraftServer server) {
        return server.getPackRepository().getSelectedIds().contains(EXTRA_PACK_ID);
    }

    /**
     * Registers the extra datapack as a required pack at the top. {@code addPackFinders} resolves
     * paths inside the mod file, so a folder elsewhere goes through {@code addRepositorySource}
     * with a {@link PathPackResources.PathResourcesSupplier} (cold-read review 2, gap 29).
     */
    private static void addExtraPack(AddPackFindersEvent event, java.nio.file.Path dir) {
        if (event.getPackType() != PackType.SERVER_DATA)
            return;
        if (!java.nio.file.Files.isRegularFile(dir.resolve("pack.mcmeta"))) {
            DeepTime.LOGGER.error("[gametest] -Ddeeptime.extraDatapack={}: no pack.mcmeta there; not added", dir);
            return;
        }
        var info = new PackLocationInfo(EXTRA_PACK_ID, Component.literal("Deep Time extra datapack: " + dir.getFileName()),
                PackSource.BUILT_IN, java.util.Optional.empty());
        Pack pack = Pack.readMetaAndCreate(info, new PathPackResources.PathResourcesSupplier(dir), PackType.SERVER_DATA,
                new PackSelectionConfig(true, Pack.Position.TOP, false));
        if (pack == null) {
            DeepTime.LOGGER.error("[gametest] -Ddeeptime.extraDatapack={}: unreadable pack.mcmeta; not added", dir);
            return;
        }
        event.addRepositorySource(consumer -> consumer.accept(pack));
        DeepTime.LOGGER.info("[gametest] extra datapack {} added as '{}'", dir, EXTRA_PACK_ID);
    }
}
